import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const result = await build({
  absWorkingDir: root,
  entryPoints: ["build/entry.js"],
  outfile: "graph-vendor.js",
  bundle: true,
  format: "iife",
  globalName: "BrainGraph3D",
  target: ["es2020"],
  minify: true,
  legalComments: "inline",
  metafile: true,
  banner: { js: "/* Generated by npm ci && npm run build in brain/web. See graph-vendor.LICENSE.txt. */" },
});

// Keep every bundled package's license alongside the redistributable bundle.
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const parts = input.split("node_modules/");
  if (parts.length < 2) continue;
  const name = parts.at(-1).split("/");
  packages.add(name[0].startsWith("@") ? name.slice(0, 2).join("/") : name[0]);
}
const notices = [];
for (const name of [...packages].sort()) {
  const dir = resolve(root, "node_modules", name);
  const pkg = JSON.parse(await readFile(resolve(dir, "package.json"), "utf8"));
  let license;
  for (const file of ["LICENSE", "LICENSE.txt", "LICENSE.md", "license", "license.txt"]) {
    try { license = await readFile(resolve(dir, file), "utf8"); break; } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  if (!license) throw new Error(`Missing license: ${name}`);
  notices.push(`${name}@${pkg.version}\n${"=".repeat(72)}\n${license.trim()}\n`);
}
await writeFile(resolve(root, "graph-vendor.LICENSE.txt"), notices.join("\n"));
const bundlePath = resolve(root, "graph-vendor.js");
const bundle = await readFile(bundlePath, "utf8");
await writeFile(bundlePath, `${bundle}\n/* Bundled third-party licenses\n${notices.join("\n").replace(/\*\//g, "* /")}\n*/\n`);
